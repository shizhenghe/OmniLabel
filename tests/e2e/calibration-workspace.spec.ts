import {expect, test} from '@playwright/test';
import {readFile} from 'node:fs/promises';

test('camera extrinsics preview immediately, export draft, save and survive reload', async ({page, request}) => {
  await page.goto('/');
  await expect(page.getByLabel('选择clip')).toHaveValue('demo');
  await expect(page.getByLabel('重建整个场景', {exact: true})).toBeEnabled();
  const original = await (await request.get('/api/clips/demo/calibration')).json();
  await page.getByLabel('编辑标定外参', {exact: true}).click();
  const editor = page.getByTestId('calibration-editor');
  await expect(editor).toBeVisible();
  await expect(page.getByLabel('外参X', {exact: true})).toBeEnabled();
  const front = page.getByTestId('camera-front');
  await expect.poll(async () => Number(await front.getAttribute('data-projected-point-count'))).toBeGreaterThan(0);
  const annotation = await front.getAttribute('data-projection-signature');
  const points = await front.getAttribute('data-raw-projection-signature');
  await page.getByLabel('外参X', {exact: true}).fill('0.2');
  await expect.poll(() => front.getAttribute('data-projection-signature')).not.toBe(annotation);
  await expect.poll(() => front.getAttribute('data-raw-projection-signature')).not.toBe(points);
  expect((await (await request.get('/api/clips/demo/calibration')).json()).revision).toBe(original.revision);
  const pending = page.waitForEvent('download');
  await page.getByLabel('导出外参', {exact: true}).click();
  const draftFile = await pending;
  const draft = JSON.parse(await readFile((await draftFile.path())!, 'utf8'));
  expect(draft.draft).toBe(true);
  expect(draft.cameras.front[0][3]).toBeCloseTo(original.cameras.front[0][3] + .2, 8);
  const saving = page.waitForResponse(r => r.request().method() === 'PUT' && r.url().endsWith('/calibration'));
  await page.getByLabel('保存外参', {exact: true}).click();
  expect((await saving).ok()).toBe(true);
  await expect(page.getByLabel('保存外参', {exact: true})).toBeDisabled();
  await page.getByLabel('关闭外参编辑', {exact: true}).click();
  await expect(editor).toHaveCount(0);
  await page.reload();
  await expect(page.getByLabel('重建整个场景', {exact: true})).toBeEnabled();
  await page.getByLabel('编辑标定外参', {exact: true}).click();
  await expect(page.getByLabel('外参X', {exact: true})).toBeEnabled();
  const saved = await (await request.get('/api/clips/demo/calibration')).json();
  expect(saved.cameras.front[0][3]).toBeCloseTo(original.cameras.front[0][3] + .2, 8);
  expect(saved.revision).not.toBe(original.revision);
  // Reloaded controls are incremental corrections to the new saved matrix.
  await expect(page.getByLabel('外参X', {exact: true})).toHaveValue('0');
});

test('LiDAR extrinsics update current scan preview, reset and persist with a stale map', async ({page, request}) => {
  await page.goto('/');
  await expect(page.getByLabel('重建整个场景', {exact: true})).toBeEnabled();
  const original = await (await request.get('/api/clips/demo/calibration')).json();
  const labels = await (await request.get('/api/clips/demo/scene/annotations')).json();
  await page.getByLabel('编辑标定外参', {exact: true}).click();
  await page.getByLabel('外参目标', {exact: true}).selectOption('__lidar__');
  const camera = page.getByTestId('camera-front');
  const initial = await camera.getAttribute('data-raw-projection-signature');
  await page.getByLabel('外参X', {exact: true}).fill('0.3');
  await expect.poll(() => camera.getAttribute('data-raw-projection-signature')).not.toBe(initial);
  await expect(page.locator('.calibration-preview-tag')).toContainText('LiDAR');
  await page.getByRole('button', {name: '还原全部', exact: true}).click();
  await expect(page.locator('.calibration-preview-tag')).toHaveCount(0);
  await expect.poll(() => camera.getAttribute('data-raw-projection-signature')).toBe(initial);
  await page.getByLabel('外参X', {exact: true}).fill('0.3');
  const saving = page.waitForResponse(r => r.request().method() === 'PUT' && r.url().endsWith('/calibration'));
  await page.getByLabel('保存外参', {exact: true}).click();
  expect((await saving).ok()).toBe(true);
  await expect(page.getByLabel('保存外参', {exact: true})).toBeDisabled();
  const saved = await (await request.get('/api/clips/demo/calibration')).json();
  expect(saved.lidar_to_ego['frame-000'][0][3]).toBeCloseTo(original.lidar_to_ego['frame-000'][0][3] + .3, 8);
  expect(saved.lidar_to_ego['frame-001']).toEqual(original.lidar_to_ego['frame-001']);
  expect((await request.get('/api/clips/demo/scene/map')).status()).toBe(404);
  expect(await (await request.get('/api/clips/demo/scene/annotations')).json()).toEqual(labels);
});
